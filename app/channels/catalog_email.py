PORT_NOTE = ("Use port 587 (STARTTLS) or 465 (SSL). Never port 25: most clouds, including Oracle Cloud, block "
             "outbound port 25.")
AUP_NOTE = ("Read the provider's acceptable-use policy: most only allow email to people who expect it. "
            "Keep volumes low and personal.")


def _sender_fields(domain_required=False):
    return [
        field("domain", "Sending domain", domain_required, placeholder="mail.yourbrand.in",
              help="A separate look-alike domain, never your main company domain itself."),
        field("from_name", "From name", True, placeholder="Your name from your company"),
        field("from_email", "From email", True, placeholder="name@mail.yourbrand.in", kind="email"),
    ]


def _smtp_fields(host_default="", host_placeholder="smtp.yourprovider.com"):
    return [
        field("smtp_host", "SMTP server", True, placeholder=host_placeholder, default=host_default or None),
        field("smtp_port", "Port", True, placeholder="587", kind="number", default="587", help=PORT_NOTE),
        field("smtp_security", "Security", True, kind="select", options=["starttls", "ssl"], default="starttls",
              help="starttls for port 587, ssl for port 465."),
        field("smtp_username", "SMTP username", True),
        field("smtp_password", "SMTP password", True, secret=True),
    ]


